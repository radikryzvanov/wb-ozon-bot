import OpenAI from "openai";
import { OPENROUTER_API_KEY } from "./config.js";

const openai = new OpenAI({
  baseURL: "https://openrouter.ai/api/v1",
  apiKey: OPENROUTER_API_KEY,
  defaultHeaders: {
    "HTTP-Referer": "https://t.me",
    "X-Title": "WB/Ozon Card Generator Bot",
  },
});

const SYSTEM_PROMPT =
  "Ты – профессиональный копирайтер для маркетплейсов Wildberries и Ozon. " +
  "Строго соблюдай правила:\n" +
  "1. Не используй эзотерические и псевдонаучные формулировки: " +
  "\"сила природы\", \"магия растений\", \"энергия\", \"целебная сила\" и подобные штампы. " +
  "Пиши конкретно и по фактам.\n" +
  "2. Латинские названия видов и сортов растений/продуктов всегда пиши на латинице " +
  "(например: Nigella sativa), не транслитерируй их на русский.\n" +
  "3. Способы применения товара должны соответствовать его реальным свойствам. " +
  "Например, горькие лечебные масла — для приёма курсом или наружного применения, " +
  "а не для добавления в кулинарные блюда как обычное растительное масло. " +
  "Не выдумывай способы использования, которые не подходят продукту.\n" +
  "4. Если товар относится к БАДам, косметическим маслам, продуктам для приёма внутрь " +
  "или другой категории, где возможны противопоказания — обязательно добавляй короткий " +
  "блок с общими предупреждениями: индивидуальная непереносимость, консультация с врачом " +
  "перед применением, не является лекарственным средством (если это БАД), беременность/" +
  "кормление грудью — по ситуации. Не ставь диагнозы и не давай медицинских советов, " +
  "только стандартное предупреждение.";

// Если бот перестанет отвечать с ошибкой 404/429 —
// значит эта бесплатная модель пропала/перегружена (список бесплатных
// моделей периодически меняется). Зайди на openrouter.ai/models,
// поставь фильтр цены "Free" и вставь сюда название другой модели
// (в формате "автор/название:free").
const MODEL = "dots-studio/dots-3-note-preview:free";

/**
 * Генерирует описание карточки товара по собранным ответам анкеты.
 * @param {{category:string,brand:string,features:string,keywords:string}} data
 * @returns {Promise<string>} готовый текст описания
 */
export async function generateDescription(data) {
  const { category, brand, features, keywords } = data;
  const productSummary =
    `Категория: ${category}\n` +
    `Бренд/материал: ${brand}\n` +
    `Особенности и преимущества: ${features}\n` +
    `Для кого и ключевые слова: ${keywords}`;

  const completion = await openai.chat.completions.create({
    model: MODEL,
    messages: [
      { role: "system", content: SYSTEM_PROMPT },
      {
        role: "user",
        content:
          `Составь продающее описание карточки товара на основе данных:\n${productSummary}\n\n` +
          "Структура:\n1. Заголовок (яркий, с ключевыми словами)\n2. Преимущества (3-4 пункта с эмодзи)\n" +
          "3. Продающий текст (2 коротких абзаца)\n4. Блок SEO-ключевых слов и хештегов",
      },
    ],
  });

  return completion.choices[0]?.message?.content || null;
}